-- Reconcile legacy employee-like user roles into EMPLOYEES while preserving
-- USERS rows, which BOOKINGS references for guest and payment history.
DECLARE
  v_employee_id NUMBER;
BEGIN
  FOR u IN (
    SELECT ID, FIRST_NAME, LAST_NAME, PHONE, ROLE
      FROM MEXMONXONALAR_TIZIMI.USERS
     WHERE LOWER(TRIM(ROLE)) IN ('employee', 'receptionist', 'housekeeper', 'cleaner', 'security', 'accountant')
     ORDER BY ID
  ) LOOP
    SELECT MIN(e.ID) INTO v_employee_id
      FROM MEXMONXONALAR_TIZIMI.EMPLOYEES e
     WHERE e.USER_ID IS NULL
       AND LOWER(TRIM(e.FIRST_NAME)) = LOWER(TRIM(u.FIRST_NAME))
       AND LOWER(TRIM(e.LAST_NAME)) = LOWER(TRIM(u.LAST_NAME))
       AND LOWER(TRIM(e.ROLE)) = LOWER(TRIM(u.ROLE))
       AND NVL(REGEXP_REPLACE(TRIM(e.PHONE), '[^0-9]', ''), '-') =
           NVL(REGEXP_REPLACE(TRIM(u.PHONE), '[^0-9]', ''), '-');

    IF v_employee_id IS NULL THEN
      INSERT INTO MEXMONXONALAR_TIZIMI.EMPLOYEES
        (FIRST_NAME, LAST_NAME, ROLE, PHONE, USER_ID, PREVIOUS_USER_ROLE, IS_ACTIVE)
      VALUES
        (u.FIRST_NAME, u.LAST_NAME, u.ROLE, u.PHONE, u.ID, 'guest', 1)
      RETURNING ID INTO v_employee_id;
    ELSE
      UPDATE MEXMONXONALAR_TIZIMI.EMPLOYEES
         SET USER_ID = u.ID, PREVIOUS_USER_ROLE = 'guest', IS_ACTIVE = 1
       WHERE ID = v_employee_id;
    END IF;

    UPDATE MEXMONXONALAR_TIZIMI.USERS SET ROLE = 'employee' WHERE ID = u.ID;
  END LOOP;
  COMMIT;
END;

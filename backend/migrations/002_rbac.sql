CREATE TABLE MEXMONXONALAR_TIZIMI.USER_PERMISSIONS (
  USER_ID NUMBER NOT NULL,
  PERMISSION_KEY VARCHAR2(40) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_USER_PERMISSIONS PRIMARY KEY (USER_ID, PERMISSION_KEY),
  CONSTRAINT FK_USER_PERMISSIONS_USER FOREIGN KEY (USER_ID)
    REFERENCES MEXMONXONALAR_TIZIMI.USERS(ID) ON DELETE CASCADE
);

-- Legacy admins retain the existing admin-panel access after migration.
INSERT INTO MEXMONXONALAR_TIZIMI.USER_PERMISSIONS (USER_ID, PERMISSION_KEY)
SELECT u.ID, p.PERMISSION_KEY
FROM MEXMONXONALAR_TIZIMI.USERS u
CROSS JOIN (
  SELECT 'dashboard' PERMISSION_KEY FROM DUAL UNION ALL
  SELECT 'bookings' FROM DUAL UNION ALL SELECT 'rooms' FROM DUAL UNION ALL
  SELECT 'roomTypes' FROM DUAL UNION ALL SELECT 'housekeeping' FROM DUAL UNION ALL
  SELECT 'services' FROM DUAL UNION ALL SELECT 'employees' FROM DUAL UNION ALL
  SELECT 'users' FROM DUAL UNION ALL SELECT 'payments' FROM DUAL UNION ALL
  SELECT 'reports' FROM DUAL UNION ALL SELECT 'settings' FROM DUAL
) p
WHERE LOWER(TRIM(u.ROLE)) = 'admin';
COMMIT;
